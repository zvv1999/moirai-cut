import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const root='/Users/zhengwei/Downloads/caption-saved-20260929';
const prior='/Users/zhengwei/Downloads/caption-layout-20260929';
const api=async(path,body)=>{const r=await fetch('http://127.0.0.1:3000/api/footage/templates'+path,{method:body?'POST':'GET',headers:{'content-type':'application/json','x-requested-with':'moirai-footage'},body:body?JSON.stringify(body):undefined});const data=await r.json();assert.ok(r.ok,JSON.stringify(data));return data;};
const application=JSON.parse(await fs.readFile(prior+'/saved-application.json','utf8'));
const style=(await api('/dynamic-assets/'+application.assetId)).definition;
assert.equal(style.revision,application.assetRevision);
assert.deepEqual(style,JSON.parse(await fs.readFile(prior+'/saved-style.json','utf8')));
const {template}=await api('/dynamic-assets/application',application);
template.id='composition-caption-saved-proof';
const samples=JSON.parse(await fs.readFile(prior+'/designs.json','utf8')).samples;
for(const sample of samples)assert.equal((await api('/inputs/'+sample.inputId)).transcript.revision,sample.transcriptRevision);
const designs=[{template,baseRevision:0}];
const manifest={name:'清晰逐词字幕 · 保存版本验证',brief:'Exact saved caption style application. Three measured inputs; inspect wrapping, highlights, backgrounds and motion. No inherited aesthetic score.',previewOnly:true,designs,samples,idempotencyKey:'caption-saved-'+createHash('sha256').update(JSON.stringify({designs,samples})).digest('hex')};
await fs.mkdir(root,{recursive:true});
for(const [name,data] of Object.entries({'style.json':style,'application.json':application,'designs.json':manifest}))await fs.writeFile(root+'/'+name,JSON.stringify(data,null,2));
const result=await api('/production/author',manifest);
await fs.writeFile(root+'/submission.json',JSON.stringify(result,null,2));
console.log(JSON.stringify({root,batchId:result.id}));
